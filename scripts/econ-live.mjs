// Server uji UI: app asli + Mongo in-memory + akun uji ber-saldo besar. Jalankan di background.
import fs from 'node:fs'
const devSrc = fs.readFileSync(new URL('../lib/dev.js', import.meta.url), 'utf8')
const hashFn = devSrc.match(/const hash53[\s\S]*?\nconst DEV_HASH/)[0].replace(/\nconst DEV_HASH$/, '')
process.env.GC_DEV_HASH = String(eval('(' + hashFn.replace('const hash53 = ', '') + ')')('uji123'))
const { MongoMemoryServer } = await import('mongodb-memory-server')
const ms = await MongoMemoryServer.create()
process.env.MONGODB_URI = ms.getUri('neyhra')
const { MongoClient } = await import('mongodb')
fs.writeFileSync('/tmp/econ-mongo-uri.txt', process.env.MONGODB_URI)
const { default: app } = await import('../lib/app.js')
const server = app.listen(4570, () => console.log('LIVE http://127.0.0.1:4570'))
const reg = await fetch('http://127.0.0.1:4570/api/auth/register', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'ujiui', password: 'rahasia123' }) }).then(r => r.json())
await fetch('http://127.0.0.1:4570/api/auth/dev/grant', { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + reg.token }, body: JSON.stringify({ code: 'uji123', coins: 500000, gems: 2000 }) })
// pity 59 + tiket cukup: pull berikut DIJAMIN ring (uji animasi khusus)
const cl = new MongoClient(process.env.MONGODB_URI); await cl.connect()
await cl.db().collection('users').updateOne({ _id: reg.uid }, { $set: { 'gacha.pity': 59, tickets: 20 } })
await cl.close()
console.log('TOKEN=' + reg.token)
process.on('SIGTERM', () => { server.close(); ms.stop().then(() => process.exit(0)) })
